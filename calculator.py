num1=int(input("enter your number:"))
num2=int(input("enter your number:"))
operation=input("operation to do:")
if operation=="+":
    print(num1+num2)
if operation=="-":
    print(num1-num2)
if operation=="*":
    print(num1*num2)
if operation=="/":
    print(num1/num2)
if operation=="**":
    print(num1**num2)
if operation=="%":
    print(num1%num2)
